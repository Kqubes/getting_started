temperature_degrees_Celsius = input("Celsius=")
temperature_degrees_kelvin = (float(temperature_degrees_Celsius)*(9/5)) + 32
temperature_degrees_fahrenheit = float(temperature_degrees_Celsius) + 273.15
print ("Temperature in Celsius =",temperature_degrees_Celsius)
print ("Temperature in Kelvin =",temperature_degrees_kelvin)
print ("Temperature in Fahrenheit =",temperature_degrees_fahrenheit)